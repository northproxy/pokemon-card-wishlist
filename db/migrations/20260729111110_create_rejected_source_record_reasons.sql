        FOREIGN KEY (rejected_source_record_id)
        REFERENCES public.rejected_source_records (
            rejected_source_record_id
        )
        ON UPDATE RESTRICT
        ON DELETE RESTRICT,

    CONSTRAINT rejected_source_record_reasons_reason_code_check
        CHECK (
            reason_code = btrim(reason_code)
