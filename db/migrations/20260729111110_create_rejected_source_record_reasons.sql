    rejected_source_record_reason_id bigint GENERATED BY DEFAULT AS IDENTITY,
    rejected_source_record_id bigint NOT NULL,
    reason_code text NOT NULL,
    field_name text,
    reason_detail text NOT NULL,
    observed_value jsonb,
    created_at timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT rejected_source_record_reasons_pkey
        PRIMARY KEY (rejected_source_record_reason_id),

    CONSTRAINT rejected_source_record_reasons_identity_key
        UNIQUE (
            rejected_source_record_id,
            reason_code,
            field_name
        ),

